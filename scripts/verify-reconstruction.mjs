import assert from 'node:assert/strict';
const origin = process.argv[2] ?? 'http://localhost:3004';
const html = await (await fetch(origin)).text();
const sections = ['hero', 'projects', 'work', 'hackathons', 'achievements', 'about'];
let previous = -1;
for (const id of sections) {
  const position = html.indexOf(`id="${id}"`);
  assert(position > previous, `${id} must follow the preceding section`);
  previous = position;
}
assert.equal((html.match(/class="project-entry /g) ?? []).length, 4);
assert.equal((html.match(/class="credential-index-entry"/g) ?? []).length, 9);
assert(html.includes('Made Undead Courier for Juice'));
assert(html.includes('Made Whisper for Shiba'));
assert(html.includes('href="#hackathons"'));
assert(html.includes('href="#about"'));
assert(!html.includes('class="issuer-filters"'));
assert(!/↗|↑|→|←/.test(html.replace(/<script[\s\S]*?<\/script>/g, '')));
assert(!html.includes('class="project-tech"'));
assert(!html.includes('credential-controls'));
assert(!html.includes('map-inset'));
assert(!html.includes('class="emboss"'));
assert(!html.includes('/maps/world.svg'));
assert.equal((html.match(/<details class="trip"/g) ?? []).length, 3);
assert.equal((html.match(/class="credential-card"/g) ?? []).length, 5);
assert(html.includes('Open Sauce'));
assert(html.includes('17–19 July 2026'));
assert.equal((html.match(/class="credential-age"/g) ?? []).length, 9);
assert.equal((html.match(/class="source-link"/g) ?? []).length, 3);
assert(html.includes('class="projects-heading"'));
const empty = await (await fetch(`${origin}/review/fixtures?state=empty`)).text();
assert(empty.includes('No credentials in this collection yet.'));
assert(empty.includes('More events to come.'));
const fixtures = await (await fetch(`${origin}/review/fixtures`)).text();
assert(fixtures.includes('San Cristóbal de las Casas'));
assert.equal((fixtures.match(/<details class="trip"/g) ?? []).length, 5);
assert.equal((fixtures.match(/class="credential-index-entry"/g) ?? []).length, 10);
assert.equal((fixtures.match(/class="experience-paper"/g) ?? []).length, 3);
assert(html.includes("Shawbrook Bank"));
assert(html.replace(/<[^>]+>/g, "").includes("Built and containerized a mortgage calculator app with a scalable architecture."));
console.log('Passed: section order, four software projects, game event details, all nine verification entries, native destinations, no-JS controls, empty collections, and growing collections.');
